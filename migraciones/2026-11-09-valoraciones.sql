-- Sprint 3: Valoraciones de cursos
-- Ejecutar una sola vez en una base que todavía no tenga esta tabla.

CREATE TABLE VALORACION_CURSO (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    ESTUDIANTE_NICK VARCHAR(255) NOT NULL,
    CURSO_ID BIGINT NOT NULL,
    PUNTUACION INT NOT NULL,
    FECHAVALORACION DATE NOT NULL,

    PRIMARY KEY (ID),

    CONSTRAINT UK_VALORACION_ESTUDIANTE_CURSO
        UNIQUE (ESTUDIANTE_NICK, CURSO_ID),

    CONSTRAINT FK_VALORACION_ESTUDIANTE
        FOREIGN KEY (ESTUDIANTE_NICK)
        REFERENCES USUARIO(NICK),

    CONSTRAINT FK_VALORACION_CURSO
        FOREIGN KEY (CURSO_ID)
        REFERENCES cursos(ID),

    CONSTRAINT CHK_VALORACION_PUNTUACION
        CHECK (PUNTUACION BETWEEN 1 AND 5)

) ENGINE=InnoDB
  DEFAULT CHARSET=utf8mb4
  COLLATE=utf8mb4_0900_ai_ci;
